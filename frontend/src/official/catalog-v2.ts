type ChoiceKey = keyof typeof choices
type Section = 1 | 2 | 3 | 4
type Entry = { section: Section; number: number; page: number; text: string; choices: ChoiceKey }
const sectionNames: Record<Section, string> = {
  1: 'Розділ 1. Культура.',
  2: 'Розділ 2. Система.',
  3: 'Розділ 3. Підзвітність.',
  4: 'Розділ 4. Рівень зрілості доброчесності у ВВНЗ (ВНП ЗВО).',
}
const sectionKeys: Record<Section, string> = { 1: 'culture', 2: 'system', 3: 'accountability', 4: 'maturity' }
const letters = 'abcdef'

function question(form: 1 | 2, entry: Entry): OfficialQuestion {
  const id = `av-f${form}-${sectionKeys[entry.section]}-${entry.number}`
  return {
    id, kind: 'single_choice', required: true, wording: 'adapted', text: entry.text,
    source: { appendix: 'В', form, page: entry.page, section: sectionNames[entry.section], number: entry.number },
    options: choices[entry.choices].map((text, index) => ({ id: `${id}-${letters[index]}`, text })),
  }
}

